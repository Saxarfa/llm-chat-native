import Foundation

/// Короткие подписи этапов ответа вместо сырых строк сервера (16.11.2026, по просьбе пользователя:
/// убрать технические слова, дубли и мелькающие «итоговые» фразы).
enum LiveStatus {
    static let fallback = "Думаю"

    /// Подпись для этапа. `nil` — итоговая фраза («Поиск завершён»), прежняя подпись остаётся.
    static func label(_ phase: String) -> String? {
        let text = phase.lowercased()
        func has(_ parts: String...) -> Bool { parts.contains { text.contains($0) } }

        if has("останавлива") { return "Останавливаю" }
        if has("ошибка генерации изображения") { return "Не удалось нарисовать" }
        if has("генерация изображения остановлена") { return "Остановлено" }
        // Текст ошибки инструмента показывать не надо: он технический.
        if has("ошибка инструмента") { return "Не вышло, пробую иначе" }
        if has("поиск завершён", "источник прочитан", "база знаний проверена", "источники google search получены") {
            return nil
        }
        if has("ожидание видеопамяти") { return "Жду своей очереди" }
        if has("сохранение", "изображение готово", "иллюстрация сохранена") { return "Сохраняю" }
        if has("продумывает", "обдумывание") { return "Думаю" }
        if has("генерация видео", "создаю видео") { return "Создаю видео" }
        if has("изображени", "nano banana", "освобождение памяти") { return "Рисую" }
        if has("поиск в базе", "чтение документа", "проверка сведений в базе") { return "Ищу в базе знаний" }
        if has("чтение найденных", "чтение источника") { return "Читаю источники" }
        if has("поиск", "поисковог") { return "Ищу в интернете" }
        if has("загрузка модели", "загружаю модель") { return "Загружаю модель" }
        if has("генерация ответа", "подготовка ответа") { return "Пишу ответ" }
        if has("проверка языка") { return "Проверяю ответ" }
        return fallback
    }
}
